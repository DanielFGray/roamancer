#!/usr/bin/env bash
set -euo pipefail

usage() {
  printf 'Usage: alchemy-staged {plan|deploy|destroy|reconcile} [Alchemy arguments...]\n' >&2
  exit 2
}

action="${1:-}"
if [[ "$#" -gt 0 ]]; then shift; fi
case "$action" in
  plan|deploy|destroy|reconcile) ;;
  *) usage ;;
esac

cli="${ALCHEMY_CLI:-}"
stack="${ALCHEMY_STACK_FILE:-staged.run.ts}"
stage="${ALCHEMY_STAGE:-staged}"
state_dir="${ALCHEMY_STATE_DIR:-$PWD}"
state_dir="$(cd -- "$state_dir" && pwd)"
state_dir="$state_dir/.alchemy"
mkdir -p -- "$state_dir"

if [[ -z "$cli" ]]; then
  printf 'ALCHEMY_CLI must point to the packaged Alchemy command\n' >&2
  exit 2
fi

nomad_env_file="${NOMAD_TOKEN_ENV_FILE:-/var/lib/nomad-acl/controller.env}"
if [[ -n "${NOMAD_TOKEN_ENV_FILE:-}" || -e "$nomad_env_file" ]]; then
  if [[ ! -r "$nomad_env_file" ]]; then
    printf 'Cannot read Nomad credentials from %s\n' "$nomad_env_file" >&2
    exit 1
  fi
  set -a
  # This file is generated by the root-owned Nomad ACL issuer.
  # shellcheck disable=SC1090
  . "$nomad_env_file"
  set +a
fi

manifest=""
case "$action" in
  plan|deploy|destroy)
    manifest="$(mktemp "$state_dir/request.XXXXXXXX.json")"
    chmod 0600 "$manifest"
    if [[ -n "${ALCHEMY_RELEASE_SET:-}" ]]; then
      cp -- "$ALCHEMY_RELEASE_SET" "$manifest"
    else
      cat > "$manifest"
    fi
    ;;
esac
cleanup() {
  if [[ -n "$manifest" ]]; then rm -f -- "$manifest"; fi
}
trap cleanup EXIT

exec 9>"$state_dir/staged-apply.lock"
flock -x 9
cd -- "$(dirname -- "$state_dir")"

run_alchemy() {
  local command="$1"
  local desired_manifest="$2"
  shift 2
  ALCHEMY_RELEASE_SET="$desired_manifest" "$cli" "$command" --stage "$stage" --config "$stack" "$@"
}

active="$state_dir/staged-active.json"
case "$action" in
  plan)
    run_alchemy plan "$manifest" "$@"
    ;;
  deploy)
    if run_alchemy deploy "$manifest" --yes "$@"; then
      cp -- "$manifest" "$active.tmp"
      chmod 0600 "$active.tmp"
      mv -f -- "$active.tmp" "$active"
    else
      status=$?
      if [[ -f "$active" ]]; then
        printf 'Deployment failed; reconciling the last accepted manifest\n' >&2
        run_alchemy deploy "$active" --yes || printf 'Recovery reconcile failed\n' >&2
      fi
      exit "$status"
    fi
    ;;
  destroy)
    if run_alchemy destroy "$manifest" "$@"; then
      rm -f -- "$active"
    else
      status=$?
      if [[ -f "$active" ]]; then
        printf 'Destroy failed; reconciling the last accepted manifest\n' >&2
        run_alchemy deploy "$active" --yes || printf 'Recovery reconcile failed\n' >&2
      fi
      exit "$status"
    fi
    ;;
  reconcile)
    if [[ -f "$active" ]]; then
      run_alchemy deploy "$active" --yes "$@"
    fi
    ;;
esac
